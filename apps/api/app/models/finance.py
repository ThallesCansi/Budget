import datetime as dt
import uuid

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    Date,
    ForeignKey,
    Index,
    SmallInteger,
    String,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base, Timestamps, UUIDPk, str_enum
from app.models.enums import AccountKind, CategoryKind, Frequency, TransactionKind


class Account(UUIDPk, Timestamps, Base):
    __tablename__ = "accounts"
    __table_args__ = (
        CheckConstraint("closing_day BETWEEN 1 AND 31", name="closing_day_range"),
        CheckConstraint("due_day BETWEEN 1 AND 31", name="due_day_range"),
        CheckConstraint(
            "kind <> 'credit_card' OR (closing_day IS NOT NULL AND due_day IS NOT NULL)",
            name="credit_card_days",
        ),
    )

    household_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("households.id", ondelete="CASCADE"), index=True
    )
    name: Mapped[str] = mapped_column(String(60))
    kind: Mapped[AccountKind] = mapped_column(str_enum(AccountKind, "account_kind"))
    initial_balance_cents: Mapped[int] = mapped_column(BigInteger, default=0)
    color: Mapped[str] = mapped_column(String(9), default="#2b478b")
    icon: Mapped[str] = mapped_column(String(40), default="wallet")
    archived: Mapped[bool] = mapped_column(Boolean, default=False)
    position: Mapped[int] = mapped_column(SmallInteger, default=0)
    # Credit cards only
    credit_limit_cents: Mapped[int | None] = mapped_column(BigInteger)
    closing_day: Mapped[int | None] = mapped_column(SmallInteger)
    due_day: Mapped[int | None] = mapped_column(SmallInteger)


class Category(UUIDPk, Timestamps, Base):
    __tablename__ = "categories"

    household_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("households.id", ondelete="CASCADE"), index=True
    )
    name: Mapped[str] = mapped_column(String(60))
    kind: Mapped[CategoryKind] = mapped_column(str_enum(CategoryKind, "category_kind"))
    color: Mapped[str] = mapped_column(String(9), default="#98a6af")
    icon: Mapped[str] = mapped_column(String(40), default="tag")
    archived: Mapped[bool] = mapped_column(Boolean, default=False)
    position: Mapped[int] = mapped_column(SmallInteger, default=0)


class RecurringRule(UUIDPk, Timestamps, Base):
    __tablename__ = "recurring_rules"
    __table_args__ = (
        CheckConstraint("amount_cents > 0", name="amount_positive"),
        CheckConstraint("interval >= 1", name="interval_positive"),
    )

    household_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("households.id", ondelete="CASCADE"), index=True
    )
    kind: Mapped[TransactionKind] = mapped_column(str_enum(TransactionKind, "recurring_kind"))
    account_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("accounts.id", ondelete="CASCADE"))
    to_account_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("accounts.id", ondelete="CASCADE")
    )
    category_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("categories.id", ondelete="SET NULL")
    )
    member_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("household_members.id", ondelete="SET NULL")
    )
    amount_cents: Mapped[int] = mapped_column(BigInteger)
    description: Mapped[str] = mapped_column(String(140))
    frequency: Mapped[Frequency] = mapped_column(str_enum(Frequency, "frequency"))
    interval: Mapped[int] = mapped_column(SmallInteger, default=1)
    start_date: Mapped[dt.date] = mapped_column(Date)
    end_date: Mapped[dt.date | None] = mapped_column(Date)
    next_occurrence: Mapped[dt.date] = mapped_column(Date)
    active: Mapped[bool] = mapped_column(Boolean, default=True)


class Transaction(Timestamps, Base):
    __tablename__ = "transactions"
    __table_args__ = (
        CheckConstraint("amount_cents > 0", name="amount_positive"),
        CheckConstraint(
            "(kind = 'transfer') = (to_account_id IS NOT NULL)", name="transfer_has_destination"
        ),
        CheckConstraint(
            "to_account_id IS NULL OR to_account_id <> account_id", name="distinct_accounts"
        ),
        Index("ix_transactions_household_date", "household_id", "date"),
        UniqueConstraint("recurring_rule_id", "recurrence_date"),
        Index(
            "uq_transactions_import_fingerprint",
            "account_id",
            "import_fingerprint",
            unique=True,
            postgresql_where=text("import_fingerprint IS NOT NULL"),
        ),
    )

    # Generated by the client so offline creation can be retried idempotently.
    id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    household_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("households.id", ondelete="CASCADE"))
    kind: Mapped[TransactionKind] = mapped_column(str_enum(TransactionKind, "transaction_kind"))
    account_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("accounts.id", ondelete="RESTRICT"), index=True
    )
    to_account_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("accounts.id", ondelete="RESTRICT"), index=True
    )
    category_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("categories.id", ondelete="SET NULL"), index=True
    )
    member_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("household_members.id", ondelete="SET NULL")
    )
    amount_cents: Mapped[int] = mapped_column(BigInteger)
    date: Mapped[dt.date] = mapped_column(Date)
    description: Mapped[str] = mapped_column(String(140))
    notes: Mapped[str | None] = mapped_column(Text)
    paid: Mapped[bool] = mapped_column(Boolean, default=True)
    # Credit card statement this entry belongs to (first day of the month).
    invoice_month: Mapped[dt.date | None] = mapped_column(Date)
    installment_group_id: Mapped[uuid.UUID | None] = mapped_column(index=True)
    installment_number: Mapped[int | None] = mapped_column(SmallInteger)
    installment_total: Mapped[int | None] = mapped_column(SmallInteger)
    recurring_rule_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("recurring_rules.id", ondelete="SET NULL")
    )
    recurrence_date: Mapped[dt.date | None] = mapped_column(Date)
    import_batch_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("import_batches.id", ondelete="SET NULL")
    )
    import_fingerprint: Mapped[str | None] = mapped_column(String(64))
    created_by: Mapped[uuid.UUID]
